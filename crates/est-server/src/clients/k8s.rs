//! Registered clients as `EstClient` objects (`est.luehr.dev/v1alpha1`),
//! watched in one namespace, so they can be kept in Git (Flux, Argo CD).

use std::sync::Arc;

use anyhow::Context;
use futures_util::StreamExt;
use kube::api::{Api, ListParams, Patch, PatchParams};
use kube::runtime::{WatchStreamExt, reflector, watcher};
use kube::{CustomResource, CustomResourceExt, ResourceExt};
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};
use serde_json::json;

use super::{Client, ClientSpec, Registry, Source, drop_duplicates};

/// A client that may get certificates for `dnsNames` with one of
/// `publicKeys`.
#[derive(CustomResource, Deserialize, Serialize, Clone, Debug, JsonSchema)]
#[kube(
    group = "est.luehr.dev",
    version = "v1alpha1",
    kind = "EstClient",
    namespaced,
    status = "EstClientStatus",
    shortname = "estc",
    printcolumn = r#"{"name":"Names","type":"string","jsonPath":".spec.dnsNames"}"#,
    printcolumn = r#"{"name":"Valid","type":"string","jsonPath":".status.conditions[?(@.type==\"Valid\")].status"}"#,
    printcolumn = r#"{"name":"Not After","type":"string","jsonPath":".status.lastIssued.notAfter"}"#,
    printcolumn = r#"{"name":"Age","type":"date","jsonPath":".metadata.creationTimestamp"}"#
)]
#[serde(rename_all = "camelCase")]
pub struct EstClientSpec {
    /// Host names the client may get certificates for (exact names, no
    /// wildcards). A request may ask for any of them.
    pub dns_names: Vec<String>,
    /// The client's keys. More than one, e.g. while it changes keys.
    pub public_keys: Vec<PublicKeyPin>,
    /// EST labels the client may use; empty for all.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub labels: Vec<String>,
}

#[derive(Deserialize, Serialize, Clone, Debug, JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct PublicKeyPin {
    /// Base64 of the SHA-256 over the DER SubjectPublicKeyInfo (RFC 7469
    /// pin-sha256); `est-server pin <file>` prints it.
    pub pin_sha256: String,
}

#[derive(Deserialize, Serialize, Clone, Debug, Default, JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct EstClientStatus {
    /// The last certificate est-server issued for this client.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub last_issued: Option<LastIssued>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub conditions: Vec<Condition>,
}

#[derive(Deserialize, Serialize, Clone, Debug, PartialEq, JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct LastIssued {
    pub serial: String,
    pub not_after: String,
    pub at: String,
    /// `simpleenroll` or `simplereenroll`.
    pub operation: String,
    pub label: String,
}

#[derive(Deserialize, Serialize, Clone, Debug, PartialEq, JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct Condition {
    #[serde(rename = "type")]
    pub type_: String,
    pub status: String,
    #[serde(default)]
    pub reason: String,
    #[serde(default)]
    pub message: String,
    #[serde(default)]
    pub observed_generation: Option<i64>,
    #[serde(default)]
    pub last_transition_time: Option<String>,
}

/// The CRD, for the Helm chart (`est-server crd`).
pub fn crd_yaml() -> String {
    let crd = EstClient::crd();
    format!(
        "# Generated by `est-server crd`; do not edit.\n{}",
        serde_yaml_ng::to_string(&crd).expect("CRD serializes")
    )
}

/// Writes `status.lastIssued`.
pub struct StatusWriter {
    client: kube::Client,
}

impl StatusWriter {
    pub fn last_issued(&self, namespace: String, name: String, issue: LastIssued) {
        let api: Api<EstClient> = Api::namespaced(self.client.clone(), &namespace);
        tokio::spawn(async move {
            let patch = json!({ "status": { "lastIssued": issue } });
            if let Err(e) = api
                .patch_status(&name, &PatchParams::default(), &Patch::Merge(patch))
                .await
            {
                tracing::warn!("EstClient {namespace}/{name}: recording the issue: {e}");
            }
        });
    }
}

/// Load the `EstClient`s of `namespace` into the registry (fails if the
/// CRD is missing or the service account may not read them) and return
/// the task that keeps them current.
pub async fn init(
    registry: Arc<Registry>,
    client: kube::Client,
    namespace: &str,
) -> anyhow::Result<impl Future<Output = ()> + use<>> {
    let api: Api<EstClient> = Api::namespaced(client.clone(), namespace);
    let list = api.list(&ListParams::default()).await.with_context(|| {
        format!("list EstClients in {namespace} (CRD installed, RBAC allows list/watch?)")
    })?;
    let _ = registry.status.set(StatusWriter { client });
    apply(&registry, &api, list.items).await;
    Ok(watch(registry, api))
}

async fn watch(registry: Arc<Registry>, api: Api<EstClient>) {
    let (reader, writer) = reflector::store::<EstClient>();
    let stream =
        reflector(writer, watcher(api.clone(), watcher::Config::default())).default_backoff();
    let mut stream = std::pin::pin!(stream);
    while let Some(event) = stream.next().await {
        match event {
            Ok(watcher::Event::Init | watcher::Event::InitApply(_)) => {}
            Ok(_) => {
                let objects = reader.state().iter().map(|o| (**o).clone()).collect();
                apply(&registry, &api, objects).await;
            }
            Err(e) => tracing::warn!("watching EstClients: {e}"),
        }
    }
}

/// Check the objects, put the good ones into the registry and tell each
/// object in `status.conditions` whether it counts.
async fn apply(registry: &Registry, api: &Api<EstClient>, objects: Vec<EstClient>) {
    let mut clients = Vec::new();
    let mut verdicts: Vec<(EstClient, Result<(), String>)> = Vec::new();
    for obj in objects {
        let namespace = obj.namespace().unwrap_or_default();
        let name = obj.name_any();
        let spec = ClientSpec {
            dns_names: obj.spec.dns_names.clone(),
            pins: obj
                .spec
                .public_keys
                .iter()
                .map(|k| k.pin_sha256.clone())
                .collect(),
            labels: obj.spec.labels.clone(),
        };
        let id = format!("kubernetes:{namespace}/{name}");
        let source = Source::Kubernetes { namespace, name };
        match Client::new(id, source, &spec) {
            Ok(c) => {
                clients.push(c);
                verdicts.push((obj, Ok(())));
            }
            Err(e) => verdicts.push((obj, Err(e))),
        }
    }
    for (id, why) in drop_duplicates(&mut clients) {
        if let Some(v) = verdicts
            .iter_mut()
            .find(|(o, _)| id.ends_with(&format!("/{}", o.name_any())))
        {
            v.1 = Err(why);
        }
    }
    let count = clients.len();
    let before = registry.kubernetes.load().len();
    registry.set_kubernetes(clients);
    if count != before {
        tracing::info!(count, "registered clients (EstClient)");
    }
    for (obj, verdict) in verdicts {
        if let Err(why) = &verdict {
            tracing::warn!("EstClient {} ignored: {why}", obj.name_any());
        }
        set_valid(api, &obj, verdict).await;
    }
}

async fn set_valid(api: &Api<EstClient>, obj: &EstClient, verdict: Result<(), String>) {
    let (status, reason, message) = match verdict {
        Ok(()) => ("True", "Accepted", String::new()),
        Err(why) => ("False", "Invalid", why),
    };
    let generation = obj.metadata.generation;
    let current = obj
        .status
        .as_ref()
        .and_then(|s| s.conditions.iter().find(|c| c.type_ == "Valid"));
    if let Some(c) = current
        && c.status == status
        && c.message == message
        && c.observed_generation == generation
    {
        return;
    }
    let condition = Condition {
        type_: "Valid".into(),
        status: status.into(),
        reason: reason.into(),
        message,
        observed_generation: generation,
        last_transition_time: match current {
            Some(c) if c.status == status => c.last_transition_time.clone(),
            _ => Some(crate::signer::cert_manager::rfc3339_now()),
        },
    };
    let mut conditions: Vec<Condition> = obj
        .status
        .as_ref()
        .map(|s| {
            s.conditions
                .iter()
                .filter(|c| c.type_ != "Valid")
                .cloned()
                .collect()
        })
        .unwrap_or_default();
    conditions.push(condition);
    let patch = json!({ "status": { "conditions": conditions } });
    if let Err(e) = api
        .patch_status(
            &obj.name_any(),
            &PatchParams::default(),
            &Patch::Merge(patch),
        )
        .await
    {
        tracing::warn!("EstClient {}: updating status: {e}", obj.name_any());
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn chart_has_the_current_crd() {
        let path = "deploy/helm/est-server/crds/estclients.est.luehr.dev.yaml";
        let file = std::fs::read_to_string(format!("{}/../../{path}", env!("CARGO_MANIFEST_DIR")))
            .unwrap_or_default();
        assert!(
            file == crd_yaml(),
            "{path} is out of date: cargo run -p est-server -- crd > {path}"
        );
    }
}
